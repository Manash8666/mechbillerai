export function decodeIndianLicensePlate(input: string): RtoLookupResult {
  if (!input) {
    return {
      isValid: false,
      plateFormatted: '',
      rawInput: '',
      stateCode: '',
      stateName: 'Unknown',
      districtCode: '',
      rtoOffice: 'Unknown RTO',
      isBharatSeries: false,
    };
  }

  const clean = input.toUpperCase().replace(/[^A-Z0-9]/g, '');

  const bhMatch = clean.match(/^(\d{2})BH(\d{1,4})([A-Z]{1,2})$/);
  if (bhMatch) {
    const year = bhMatch[1];
    const seq = bhMatch[2].padStart(4, '0');
    const series = bhMatch[3];
    return {
      isValid: true,
      plateFormatted: `${year} BH ${seq} ${series}`,
      rawInput: input,
      stateCode: 'BH',
      stateName: 'India (Bharat Series)',
      districtCode: 'BH',
      rtoOffice: 'Central MoRTH / Pan-India Transferable Permit',
      isBharatSeries: true,
      vehicleClassHint: `Registered in 20${year} (Defense/Central Govt/Private Multi-State)`,
    };
  }

  const stdMatch = clean.match(/^([A-Z]{2})(\d{1,2})([A-Z]{0,3})(\d{1,4})$/);
  if (stdMatch) {
    const state = stdMatch[1];
    const dist = stdMatch[2].padStart(2, '0');
    const series = stdMatch[3] || '';
    const number = stdMatch[4].padStart(4, '0');

    const stateName = INDIAN_STATES[state] || `State (${state})`;
    const districtName = RTO_DISTRICTS[state]?.[dist] || `RTO Office (${state}-${dist})`;

    const formatted = series
      ? `${state}-${dist}-${series}-${number}`
      : `${state}-${dist}-${number}`;

    return {
      isValid: true,
      plateFormatted: formatted,
      rawInput: input,
      stateCode: state,
      stateName,
      districtCode: dist,
      rtoOffice: districtName,
      isBharatSeries: false,
      vehicleClassHint: series ? `Series ${series}` : undefined,
    };
  }

  const prefixMatch = clean.match(/^([A-Z]{2})(\d{1,2})/);
  if (prefixMatch) {
    const state = prefixMatch[1];
    const dist = prefixMatch[2].padStart(2, '0');
    const stateName = INDIAN_STATES[state];
    const districtName = RTO_DISTRICTS[state]?.[dist];

    if (stateName) {
      return {
        isValid: false,
        plateFormatted: clean,
        rawInput: input,
        stateCode: state,
        stateName,
        districtCode: dist,
        rtoOffice: districtName || `${stateName} District ${dist}`,
        isBharatSeries: false,
      };
    }
  }

  return {
    isValid: false,
    plateFormatted: clean,
    rawInput: input,
    stateCode: '',
    stateName: 'Unrecognized State',
    districtCode: '',
    rtoOffice: 'Unrecognized RTO Office',
    isBharatSeries: false,
  };
}
